// Writes docs/STYLES_LIST.md: a table of all built-in styles (id, name, category, one-line description).
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const { CATEGORIES, byPopularity } = await import("../src/lib/styleModel.ts");
const dir = join(process.cwd(), "resources", "styles");
const styles = readdirSync(dir)
  .filter((n) => n.endsWith(".json") && n !== "package.json")
  .map((n) => JSON.parse(readFileSync(join(dir, n), "utf8")));
const firstSentence = (text) => (text.match(/^.*?[.!?](?=\s|$)/)?.[0] ?? text).trim();
const rows = [];
for (const category of CATEGORIES) {
  for (const s of styles.filter((x) => x.category === category).sort(byPopularity)) {
    rows.push(`| ${s.id} | ${s.name} | ${s.category} | ${firstSentence(s.core_identity).replace(/\|/g, "/")} |`);
  }
}
const text = `# Built-in styles

${styles.length} styles in ${CATEGORIES.length} categories, in the order the style picker shows them (most popular first). Generated by \`npm run styles:list\` from resources/styles; do not edit by hand.

| Id | Name | Category | Description |
|---|---|---|---|
${rows.join("\n")}
`;
writeFileSync(join(process.cwd(), "docs", "STYLES_LIST.md"), text);
console.log(`Wrote docs/STYLES_LIST.md with ${rows.length} styles.`);
